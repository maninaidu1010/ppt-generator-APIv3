def pick_icon(text: str, index: int = 0) -> str:
    """Choose an icon key from text; fall back to a rotation so neighbours differ."""
    import re
    t = (text or "").lower()
    for pattern, key in KEYWORDS:
        if re.search(pattern, t):
            return key
    return FALLBACK_ROTATION[index % len(FALLBACK_ROTATION)]


